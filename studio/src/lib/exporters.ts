import runtimeSource from "@/runtime/stylescape-runtime.js?raw";
import { RUNTIME_VERSION, type Scene } from "@/runtime/stylescape-runtime.js";

export { runtimeSource };

export function slug(s: string) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "scene";
}

export function sceneJSON(scene: Scene) {
  return JSON.stringify(scene, null, 2);
}

function escapeHtml(s: string) {
  return s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c] as string);
}

export function standaloneHTML(scene: Scene) {
  const safeJson = sceneJSON(scene).replace(/</g, "\\u003c");
  const safeRuntime = runtimeSource.replace(/<\/script/gi, "<\\/script");
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${escapeHtml(scene.name)} - Style Scape</title>
<style>html,body{margin:0;height:100%;background:${scene.palette.background}}canvas{display:block;width:100vw;height:100vh}</style>
</head>
<body>
<canvas id="stylescape" aria-label="${escapeHtml(scene.name)}"></canvas>
<script type="module">
/* Style Scape runtime ${RUNTIME_VERSION} (inlined) */
${safeRuntime}
const scene = ${safeJson};
const inst = createStyleScape(document.getElementById("stylescape"), scene, {
  maxDpr: 2,
  onError: (e) => console.warn(e.message),
});
window.addEventListener("pagehide", () => inst.dispose());
</script>
</body>
</html>
`;
}

export function reactComponent(scene: Scene) {
  return `// StyleScape.jsx - generated by Style Scape ${RUNTIME_VERSION}
// Place next to stylescape-runtime.js (download it from the same export dialog).
import { useEffect, useRef } from "react";
import { createStyleScape } from "./stylescape-runtime.js";

export const scene = ${sceneJSON(scene)};

export default function StyleScape({ scene: s = scene, animate = true, maxDpr = 2, style, className }) {
  const ref = useRef(null);
  const inst = useRef(null);
  useEffect(() => {
    inst.current = createStyleScape(ref.current, s, { animate, maxDpr });
    return () => { inst.current?.dispose(); inst.current = null; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [animate, maxDpr]);
  useEffect(() => { inst.current?.update(s); }, [s]);
  return (
    <canvas
      ref={ref}
      className={className}
      style={{ display: "block", width: "100%", height: "100%", ...style }}
      aria-label={s.name}
    />
  );
}
`;
}

export function download(filename: string, data: string | Blob, mime = "text/plain") {
  const blob = typeof data === "string" ? new Blob([data], { type: mime }) : data;
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}

export async function dataURLToBlob(url: string) {
  const res = await fetch(url);
  return res.blob();
}
